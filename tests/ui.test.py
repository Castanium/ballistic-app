"""Tests navigateur (Playwright + Edge). Necessite un serveur HTTP sur la racine du projet.
Usage :
  uv run --no-project python -m http.server 8765 --bind 127.0.0.1   (dans un autre terminal)
  uv run --no-project --with playwright python tests/ui.test.py [http://127.0.0.1:8765/]
Captures dans tests/screens/."""
import sys, os, asyncio, re
from playwright.async_api import async_playwright

URL = sys.argv[1] if len(sys.argv) > 1 else "http://127.0.0.1:8765/"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "screens")
os.makedirs(OUT, exist_ok=True)
results = []

def check(name, cond, info=""):
    results.append((name, bool(cond), info))
    print(("  ok  " if cond else "  FAIL ") + name + ("" if cond else "  -> " + str(info)))

BAD = re.compile(r"\b(NaN|Infinity|undefined|null)\b")

async def no_bad_text(pg, label):
    txt = await pg.evaluate("document.querySelector('main').innerText + document.querySelector('.topbar').innerText")
    m = BAD.search(txt)
    check(f"aucun NaN/Infinity/undefined affiche ({label})", not m, m and txt[max(0, m.start() - 40):m.end() + 40])

async def setv(pg, sel, v):
    await pg.fill(sel, str(v))
    await pg.wait_for_timeout(30)

async def tab(pg, t):
    await pg.click(f".tabs [data-tab={t}]")
    await pg.wait_for_timeout(60)

async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(channel="msedge")
        ctx = await b.new_context(viewport={"width": 390, "height": 844}, device_scale_factor=2, has_touch=True, is_mobile=True)
        pg = await ctx.new_page()
        errors = []
        pg.on("pageerror", lambda e: errors.append(str(e)))
        pg.on("console", lambda m: m.type == "error" and errors.append(m.text))
        pg.on("dialog", lambda d: asyncio.ensure_future(d.accept()))
        await pg.goto(URL)
        await pg.wait_for_function("window.App && App.solution")
        await pg.wait_for_timeout(1700)  # splash

        print("Calc")
        el = await pg.text_content("#o-elev")
        check("reference .308 : elevation 4.02 MIL affichee", el.startswith("4.02"), el)
        check("reference : 40 clics a 0.1 MIL", "40" in await pg.text_content("#o-elevClk"))
        check("reference : vent 0.85 MIL / 8 clics", (await pg.text_content("#o-wind")).startswith("0.85") and "8" in await pg.text_content("#o-windClk"))
        check("reference : MOA 13.81 affiche", "13.81" in await pg.text_content("#o-elev2"))
        await setv(pg, "#in-distance", 800)
        el8 = await pg.text_content("#o-elev")
        check("25. recalcul dynamique (800 m)", el8.startswith("9.18"), el8)
        await pg.click("[data-step='in-distance:-1']")
        check("stepper distance -25 m", await pg.input_value("#in-distance") == "775")
        await setv(pg, "#in-distance", 500)
        # cadran : clic sur 12h -> derive nulle
        box = await pg.locator("#windClock").bounding_box()
        await pg.mouse.click(box["x"] + box["width"] / 2, box["y"] + box["height"] * 0.12)
        await pg.wait_for_timeout(50)
        d12 = await pg.evaluate("App.solution.drift")
        check("14. cadran 12h (vent de face) : derive nulle", abs(d12) < 1e-9 and await pg.evaluate("App.state.session.windClock") == 12, d12)
        await pg.mouse.click(box["x"] + box["width"] * 0.12, box["y"] + box["height"] / 2)
        await pg.wait_for_timeout(50)
        check("cadran 9h : derive vers la droite", await pg.evaluate("App.state.session.windClock === 9 && App.solution.drift > 0"))
        await pg.mouse.click(box["x"] + box["width"] * 0.88, box["y"] + box["height"] / 2)
        await pg.wait_for_timeout(50)
        # unites
        await pg.click("[data-cycle=distUnit]")
        check("m -> yd : champ converti (500 m = 546.8 -> 547 yd)", await pg.input_value("#in-distance") == "547", await pg.input_value("#in-distance"))
        await pg.click("[data-cycle=distUnit]")
        check("yd -> m : retour 500", await pg.input_value("#in-distance") == "500", await pg.input_value("#in-distance"))
        await pg.click("#ammoBox summary")
        await pg.click("[data-cycle=velocityUnit]")
        check("fps -> m/s dans le champ (792.5)", await pg.input_value("#in-mv") == "792.5", await pg.input_value("#in-mv"))
        await pg.click("[data-cycle=velocityUnit]")
        check("m/s -> fps (2600)", await pg.input_value("#in-mv") == "2600", await pg.input_value("#in-mv"))
        # erreurs
        await setv(pg, "#in-bc", 0)
        check("23. BC = 0 : erreur affichee, pas de solution", await pg.is_visible("#solErr") and not await pg.is_visible("#solOk"))
        await no_bad_text(pg, "BC=0")
        await setv(pg, "#in-bc", "")
        check("BC vide : erreur", await pg.is_visible("#solErr"))
        await setv(pg, "#in-bc", "0,243")
        check("virgule decimale acceptee (0,243)", await pg.is_visible("#solOk") and await pg.evaluate("P => App.state.profiles[0].bc", None) == 0.243)
        await setv(pg, "#in-distance", -5)
        check("distance negative refusee", await pg.is_visible("#solErr"))
        await pg.evaluate("document.getElementById('atmoBox').open = true")
        await setv(pg, "#in-temp", 200)
        check("temperature impossible refusee", await pg.is_visible("#solErr"))
        await no_bad_text(pg, "temp 200")
        await setv(pg, "#in-temp", 15); await setv(pg, "#in-distance", 500)
        await pg.click("#ammoBox summary")
        # valeur de clic
        await pg.click("#segClick [data-click=moa_1_4]")
        check("24. 1/4 MOA : 55 clics, unite MOA", "55" in await pg.text_content("#o-elevClk") and "MOA" in await pg.text_content("#o-elev"))
        await pg.click("#segClick [data-click=moa_1_8]")
        check("1/8 MOA : 110 clics", "110" in await pg.text_content("#o-elevClk"))
        await pg.click("#segClick [data-click=mil_0_2]")
        check("0.2 MIL : 20 clics", "20" in await pg.text_content("#o-elevClk"))
        await pg.click("#segClick [data-click=mil_0_1]")
        await no_bad_text(pg, "calc")
        await pg.screenshot(path=os.path.join(OUT, "calc_portrait.png"))

        print("Reticule / point d'impact")
        await tab(pg, "reticle")
        for t in ["mildot", "moa", "xmas", "bdc"]:
            await pg.click(f"#segRet [data-ret={t}]")
            m = await pg.evaluate("""() => { const r = App.reticle, c = document.getElementById('impact'), H = r.halfSpanMil;
              const vb = document.getElementById('reticle').viewBox.baseVal;
              return { cx: c ? +c.getAttribute('cx') : null, cy: c ? +c.getAttribute('cy') : null, x: r.x, y: r.y, H, vbw: vb.width,
                       expX: -App.solution.windRad * 1000, expY: -App.solution.elevRad * 1000, oov: r.outOfView, type: r.type } }""")
            if m["oov"]:
                check(f"23. {t} : impact hors champ signale", await pg.is_visible("#retOov"))
            else:
                check(f"§25 {t} : cx SVG = correction vent (MIL)", abs(m["cx"] - m["expX"]) < 1e-9, m)
                check(f"§25 {t} : cy SVG = -(-elevation) (MIL, y vers le bas)", abs(-m["cy"] - m["expY"]) < 1e-9, m)
                check(f"{t} : viewBox = 2 x demi-champ", abs(m["vbw"] - 2 * m["H"]) < 1e-5)
        await pg.click("#segRet [data-ret=xmas]")
        cy0 = float(await pg.get_attribute("#impact", "cy"))
        await pg.click("[data-pad=up]")
        cy1 = float(await pg.get_attribute("#impact", "cy"))
        check("+1 clic vertical : impact monte de 0.1 MIL exactement", abs((cy0 - cy1) - 0.1) < 1e-9, (cy0, cy1))
        check("affichage VERT +1", await pg.input_value("#in-cv") == "+1")
        cx0 = float(await pg.get_attribute("#impact", "cx"))
        await pg.click("[data-pad=right]"); await pg.click("[data-pad=right]")
        cx1 = float(await pg.get_attribute("#impact", "cx"))
        check("+2 clics horizontaux : impact a droite de 0.2 MIL", abs((cx1 - cx0) - 0.2) < 1e-9, (cx0, cx1))
        await pg.click("[data-pad=down]"); await pg.click("[data-pad=left]")
        check("- clic vertical / - clic horizontal", await pg.evaluate("App.state.session.clicksV === 0 && App.state.session.clicksH === 1"))
        await pg.fill("#in-cv", "25")
        check("saisie directe 25 clics", await pg.evaluate("App.state.session.clicksV") == 25)
        await pg.click("[data-sign=clicksV]")
        check("inversion de signe -> -25", await pg.evaluate("App.state.session.clicksV") == -25)
        await pg.click("#btnApply")
        r = await pg.evaluate("[App.reticle.impactV, App.reticle.impactH, App.state.session.clicksV, App.state.session.clicksH]")
        check("appliquer solution : impact au centre (< 1/2 clic)", abs(r[0]) <= 5e-5 + 1e-12 and abs(r[1]) <= 5e-5 + 1e-12 and r[2] == 40 and r[3] == 8, r)
        await pg.screenshot(path=os.path.join(OUT, "reticle_portrait.png"))
        await tab(pg, "calc")
        await pg.click("#segClick [data-click=mil_0_2]")
        check("changement de clic : clics convertis (40 x 0.1 -> 20 x 0.2)", await pg.evaluate("App.state.session.clicksV") == 20)
        await pg.click("#segClick [data-click=mil_0_1]")
        await tab(pg, "reticle")
        await pg.click("#btnZero")
        check("remise a zero", await pg.evaluate("App.state.session.clicksV === 0 && App.state.session.clicksH === 0"))
        await no_bad_text(pg, "reticule")

        print("Calibrage")
        await tab(pg, "calib")
        check("calibrage vide : message", await pg.is_visible("#calEmpty"))
        await setv(pg, "#c-dist", 30); await pg.click("#calForm button[type=submit]")
        check("distance de calibrage invalide refusee", await pg.evaluate("App.state.profiles[0].calibration.length") == 0)
        await setv(pg, "#c-dist", 600); await setv(pg, "#c-dv", -10)
        conv = await pg.text_content("#c-dv-conv")
        check("conversion directe -10 cm @600 m = -0.57 MOA / -0.17 MIL", "-0.57 MOA" in conv and "-0.17 MIL" in conv, conv)
        await pg.click("#calForm button[type=submit]")
        await pg.wait_for_timeout(100)
        check("17. mono-distance : BC calibre affiche, statut INDICATIF", (await pg.text_content("#cr-bc")) not in ("--", "") and "INDICATIF" in await pg.text_content("#calBadge"))
        row = await pg.text_content("#calTable tbody tr")
        check("tableau : distance, ecarts, MOA, MIL", "600" in row and "-10.0" in row and "-0.57" in row and "-0.17" in row, row)
        for d, v in [(800, -24), (400, -4)]:
            await setv(pg, "#c-dist", d); await setv(pg, "#c-dv", v); await pg.click("#calForm button[type=submit]")
        await pg.wait_for_timeout(100)
        check("18. multi-distance : 3 distances", "3 /" in await pg.text_content("#cr-n"))
        bc = float(await pg.text_content("#cr-bc"))
        check("BC calibre < BC fabricant (impacts bas)", bc < 0.243, bc)
        await pg.click("#btnUseCal")
        check("BC calibre utilise dans Calc", await pg.evaluate("App.solution.input.bc") == await pg.evaluate("App.state.profiles[0].bcCalibrated"))
        check("indicateur BC CAL. dans la barre", await pg.is_visible("#bcFlag"))
        bc_before = await pg.evaluate("App.state.profiles[0].bcCalibrated")
        await tab(pg, "calc")
        await pg.evaluate("document.getElementById('ammoBox').open = true")
        await setv(pg, "#in-mv", 2560)
        await pg.wait_for_timeout(1500)
        bc_after = await pg.evaluate("App.state.profiles[0].bcCalibrated")
        check("BC calibre recalcule apres correction de vitesse dans Calc (sans ouvrir Calibrage)", bc_after > bc_before + 0.005 and await pg.evaluate("App.solution.input.bc") == bc_after, (bc_before, bc_after))
        await setv(pg, "#in-mv", 2600)
        await pg.wait_for_timeout(1500)
        await tab(pg, "calib")
        await pg.click("#calTable tbody tr:first-child .del")
        check("suppression d'un point", await pg.evaluate("App.state.profiles[0].calibration.length") == 2)
        await no_bad_text(pg, "calibrage")
        await pg.screenshot(path=os.path.join(OUT, "calib_portrait.png"), full_page=True)

        print("Profils")
        await tab(pg, "profiles")
        n0 = await pg.evaluate("App.state.profiles.length")
        await pg.click("#btnNewProf")
        await setv(pg, "#p-name", "")
        await pg.click("#profSave")
        check("profil sans nom refuse", await pg.is_visible("#profDlg") and await pg.evaluate("App.state.profiles.length") == n0)
        await setv(pg, "#p-name", "6mm Dasher, 105gr"); await setv(pg, "#p-caliber", "6mm Dasher")
        await setv(pg, "#p-mv", 2950); await setv(pg, "#p-bc", 0.275); await pg.select_option("#p-dm", "G7")
        await pg.select_option("#p-ret", "bdc"); await pg.select_option("#p-click", "moa_1_8")
        await pg.click("#profSave")
        await pg.wait_for_timeout(80)
        check("19. creation profil : ajoute et actif", await pg.evaluate("App.state.profiles.length") == n0 + 1 and await pg.evaluate("App.state.profiles.at(-1).id === App.state.activeProfileId"))
        check("22. profil actif : reticule et clic restaures", await pg.evaluate("App.reticle.type === 'bdc' && App.reticle.clickId === 'moa_1_8'"))
        check("profil actif : vitesse 2950 fps", abs(await pg.evaluate("App.solution.input.mv") - 2950 * 0.3048) < 1e-9)
        await pg.click(".pcard:last-child [data-act=edit]")
        await setv(pg, "#p-name", "6mm Dasher, 105gr Hybrid"); await setv(pg, "#p-bc", 0.28)
        await pg.click("#profSave"); await pg.wait_for_timeout(60)
        check("20. modification profil", await pg.evaluate("App.state.profiles.at(-1).name") == "6mm Dasher, 105gr Hybrid" and await pg.evaluate("App.solution.input.bc") == 0.28)
        await pg.click(".pcard:last-child [data-act=dup]")
        check("duplication", await pg.evaluate("App.state.profiles.length") == n0 + 2 and "(copie)" in await pg.evaluate("App.state.profiles.at(-1).name"))
        await pg.click(".pcard:first-child .pick")
        check("22. changement de profil : .308 restaure", await pg.evaluate("App.reticle.type === 'xmas' && App.solution.input.dragModel === 'G7'") and "308" in await pg.text_content("#profName"))
        await pg.click(".pcard:last-child [data-act=del]")
        await pg.wait_for_timeout(60)
        check("21. suppression profil", await pg.evaluate("App.state.profiles.length") == n0 + 1)
        await no_bad_text(pg, "profils")
        await pg.screenshot(path=os.path.join(OUT, "profiles_portrait.png"))

        print("Persistance")
        snap = await pg.evaluate("JSON.stringify({p: App.state.profiles.map(p => [p.name, p.bc, p.reticle, p.clickId, p.calibration.length]), a: App.state.activeProfileId, s: App.state.session.distance})")
        await pg.evaluate("document.dispatchEvent(new Event('visibilitychange'))")
        await pg.wait_for_timeout(400)
        await pg.reload(); await pg.wait_for_function("window.App && App.solution")
        snap2 = await pg.evaluate("JSON.stringify({p: App.state.profiles.map(p => [p.name, p.bc, p.reticle, p.clickId, p.calibration.length]), a: App.state.activeProfileId, s: App.state.session.distance})")
        check("26. apres rechargement : profils, actif, calibrage, session identiques", snap == snap2, (snap, snap2))
        check("26. onglet restaure", await pg.evaluate("App.state.session.tab") == "profiles")
        # corruption injectee avant le chargement (sinon la sauvegarde pagehide la recouvre)
        await pg.add_init_script("if (!sessionStorage.getItem('corrupt')) { sessionStorage.setItem('corrupt', '1'); localStorage.setItem('ballistic.v1', '{corrompu'); }")
        await pg.reload(); await pg.wait_for_function("window.App && App.solution")
        check("donnees corrompues : app fonctionnelle + message", await pg.evaluate("App.state.profiles.length") == 2 and await pg.is_visible("#toast"))
        check("donnees corrompues : copie de secours conservee", await pg.evaluate("localStorage.getItem('ballistic.v1.corrupt')") == "{corrompu")

        print("Hors ligne")
        ready = await pg.evaluate("navigator.serviceWorker.ready.then(() => !!navigator.serviceWorker.controller || 'pending')")
        if ready == "pending":
            await pg.reload(); await pg.wait_for_function("window.App && App.solution")
        check("service worker actif", await pg.evaluate("!!navigator.serviceWorker.controller"))
        await ctx.set_offline(True)
        await pg.reload(); await pg.wait_for_function("window.App && App.solution", timeout=8000)
        await pg.wait_for_timeout(1700)
        await tab(pg, "calc")
        check("27. hors ligne : app chargee et calcul OK", (await pg.text_content("#o-elev")).startswith("4.02"))
        logo_ok = await pg.evaluate("document.querySelector('.watermark').naturalWidth > 0")
        check("hors ligne : logo depuis le cache", logo_ok)
        await ctx.set_offline(False)

        print("Responsive")
        for name, w, h in [("se_portrait", 375, 667), ("portrait", 390, 844), ("landscape", 844, 390), ("se_landscape", 667, 375), ("android", 412, 915), ("desktop", 1440, 900)]:
            await pg.set_viewport_size({"width": w, "height": h})
            for t in ["calc", "reticle", "calib", "profiles"]:
                await tab(pg, t)
                ov = await pg.evaluate("document.documentElement.scrollWidth - window.innerWidth")
                check(f"{name} {w}x{h} {t} : pas de debordement horizontal", ov <= 0, ov)
                await pg.screenshot(path=os.path.join(OUT, f"{name}_{t}.png"))
            await tab(pg, "reticle")
            vis = await pg.evaluate("(() => { const r = document.querySelector('.ret-view').getBoundingClientRect(), n = document.querySelector('.tabs').getBoundingClientRect(); return [Math.round(r.width), Math.round(r.bottom), Math.round(n.top)] })()")
            check(f"{name} : reticule visible au-dessus de la navigation", vis[1] <= vis[2] + 1 and vis[0] >= 180, vis)
            small = await pg.evaluate("""[...document.querySelectorAll('.screen.active button, .tabs button')].filter(b => b.offsetParent && !b.closest('.rt')).map(b => b.getBoundingClientRect()).filter(r => r.height < 36 || r.width < 36).length""")
            check(f"{name} : cibles tactiles >= 36 px (reticule)", small == 0, small)

        check("aucune erreur JS", not errors, errors)
        await b.close()
    ok = sum(1 for r in results if r[1])
    print(f"\n{ok} ok, {len(results) - ok} echec(s)")
    sys.exit(0 if ok == len(results) else 1)

asyncio.run(main())
